package cmd

import (
	"fmt"
	"io"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// WriteReference writes every command and flag as the CLI reference page in the docs, so the page can't drift from the code.
func WriteReference(w io.Writer) {
	fmt.Fprint(w, `---
title: CLI reference
description: Every skiff command and flag, generated from the CLI itself.
---

{/* Generated by WriteReference in cmd/reference.go. Run SKIFF_UPDATE_DOCS=1 go test ./cmd -run TestCLIReference to refresh it. */}
`)
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		for _, sub := range c.Commands() {
			if sub.Hidden || !sub.IsAvailableCommand() || sub.Name() == "help" || sub.Name() == "completion" {
				continue
			}
			writeCommand(w, sub)
			walk(sub)
		}
	}
	walk(newRootCmd())
}

func writeCommand(w io.Writer, c *cobra.Command) {
	level := "##"
	if c.Parent() != nil && c.Parent().HasParent() {
		level = "###"
	}
	fmt.Fprintf(w, "\n%s %s\n\n%s\n", level, c.CommandPath(), mdxText(c.Short))
	if long := strings.TrimSpace(c.Long); long != "" && long != c.Short {
		fmt.Fprintf(w, "\n%s\n", mdxText(strings.ReplaceAll(long, "\n", " ")))
	}
	if c.Runnable() {
		fmt.Fprintf(w, "\n```sh\n%s\n```\n", c.UseLine())
	}
	var flags []*pflag.Flag
	c.NonInheritedFlags().VisitAll(func(f *pflag.Flag) {
		if !f.Hidden && f.Name != "help" {
			flags = append(flags, f)
		}
	})
	if len(flags) == 0 {
		return
	}
	fmt.Fprint(w, "\n| Flag | Default | What it does |\n| --- | --- | --- |\n")
	for _, f := range flags {
		name := "`--" + f.Name + "`"
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		def := f.DefValue
		if def == "" || def == "[]" || f.Value.Type() == "bool" && def == "false" {
			def = ""
		} else {
			def = "`" + def + "`"
		}
		fmt.Fprintf(w, "| %s | %s | %s |\n", name, def, strings.ReplaceAll(mdxText(f.Usage), "|", `\|`))
	}
}

// mdxText keeps prose from being read as MDX: braces would start an expression and < a tag.
func mdxText(s string) string {
	return strings.NewReplacer("{", `\{`, "}", `\}`, "<", "&lt;", ">", "&gt;").Replace(strings.TrimSpace(s))
}
